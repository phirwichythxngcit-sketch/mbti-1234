def _has_category(cat_scores, keywords):
    for category, score in cat_scores.items():
        text = str(category).lower()
        if any(str(keyword).lower() in text for keyword in keywords) and float(score) >= 6:
            return True
    return False


def get_faculty_results(mbti, cat_scores):
    results = {}
    for proposition, (name, primary, secondary) in FACULTY_PROPOSITIONS.items():
        primary_ok = _has_category(cat_scores, primary)
        secondary_ok = True if not secondary else _has_category(cat_scores, secondary)
        mbti_ok = mbti in MBTI_BY_FACULTY[proposition]
        results[proposition] = {
            "name": name,
            "value": mbti_ok and primary_ok and secondary_ok,
            "mbti_ok": mbti_ok,
            "interest_ok": primary_ok and secondary_ok,
        }
    return results


def funding_level_from_average(average):
    if average >= 4:
        return "high"
    if average >= 3:
        return "medium"
    return "low"
