def init_state() -> None:
    if "page" not in st.session_state:
        st.session_state.page = 0
    if "answers" not in st.session_state:
        st.session_state.answers = {}


def reset_assessment() -> None:
    st.session_state.page = 0
    st.session_state.answers = {}
    for key in list(st.session_state.keys()):
        if key.startswith("input_") or key.startswith("select_"):
            del st.session_state[key]


def likert_value(value: str) -> int:
    return LIKERT.index(value) + 1


def calculate_scores() -> tuple[dict[str, float], dict[str, float], dict[str, float]]:
    function_scores: dict[str, float] = {}
    for function in FUNCTIONS:
        values = [
            st.session_state.answers.get(f"cognitive_{function['key']}_{index}", 3)
            for index in range(len(function["questions"]))
        ]
        function_scores[function["key"]] = round(sum(values) / len(values) * 20, 1)

    interest_scores: dict[str, float] = {}
    for interest in INTERESTS:
        values = [
            st.session_state.answers.get(f"interest_{interest['key']}_{index}", 3)
            for index in range(len(interest["items"]))
        ]
        interest_scores[interest["name"]] = round(sum(values) / len(values) * 20, 1)

    goal_scores: dict[str, float] = {}
    for index, goal in enumerate(WORK_GOALS):
        goal_scores[goal] = round(st.session_state.answers.get(f"goal_{index}", 3) * 20, 1)
    return function_scores, interest_scores, goal_scores


def infer_mbti(function_scores: dict[str, float]) -> tuple[str, dict[str, float]]:
    fit_scores: dict[str, float] = {}
    weights = [0.4, 0.3, 0.2, 0.1]
    for mbti, stack in MBTI_STACKS.items():
        fit_scores[mbti] = round(sum(function_scores[fn] * weight for fn, weight in zip(stack, weights)), 1)
    best_type = max(fit_scores, key=fit_scores.get)
    return best_type, fit_scores


def completed_cognitive_count() -> int:
    return sum(
        1
        for function in FUNCTIONS
        for index in range(len(function["questions"]))
        if f"cognitive_{function['key']}_{index}" in st.session_state.answers
    )


