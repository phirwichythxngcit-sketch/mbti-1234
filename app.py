def render_score_rows(scores: dict[str, float], color: str = "#d66d55") -> None:
    for name, score in sorted(scores.items(), key=lambda item: item[1], reverse=True):
        label_col, bar_col, value_col = st.columns([1.5, 4, 0.5])
        with label_col:
            st.write(f"**{name}**")
        with bar_col:
            st.progress(int(score))
        with value_col:
            st.write(f"{score:.0f}")


def get_constraints() -> dict[str, str]:
    return {
        key: st.session_state.answers.get(f"select_{key}", "")
        for key in ["budget", "job_style", "burden", "scholarship", "location"]
    }


def render_path_recommendations(
    mbti: str,
    function_scores: dict[str, float],
    interest_scores: dict[str, float],
    goal_scores: dict[str, float],
    constraints: dict[str, str],
) -> None:
    top_interests = sorted(interest_scores.items(), key=lambda item: item[1], reverse=True)[:3]
    stack = MBTI_STACKS[mbti]
    profile = TYPE_PROFILES[mbti]
    st.markdown("### เส้นทางที่น่าลองสำรวจ")
    st.caption("ลำดับนี้มาจากคะแนนความสนใจ + ความสอดคล้องกับ Cognitive Function ใน stack ของคุณ ไม่ใช่คำสั่งให้เลือกอาชีพตายตัว")

    for rank, (interest_name, interest_score) in enumerate(top_interests, start=1):
        interest_data = next(item for item in INTERESTS if item["name"] == interest_name)
        overlap = [fn for fn in stack if fn in interest_data["functions"]]
        career_text = " · ".join(CAREER_MAP[interest_name][:4])
        st.markdown(
            f"""
            <div class="section-card">
            <b>{rank:02d} · {interest_name}</b> <span style="color:#d66d55">คะแนน {interest_score:.0f}/100</span><br/>
            <span class="small-note">อาชีพที่ควรหาข้อมูลเพิ่ม: {career_text}</span><br/>
            <span class="small-note">เพราะ stack ของคุณมี {', '.join(overlap) if overlap else 'ฟังก์ชันที่ใกล้เคียง'} ซึ่งช่วยหนุนการเรียนรู้ด้านนี้</span>
            </div>
            """,
            unsafe_allow_html=True,
        )

    budget = constraints["budget"]
    if budget.startswith("จำกัด"):
        study_route = "เริ่มจากมหาวิทยาลัยรัฐใกล้บ้าน มหาวิทยาลัยเปิด หรือหลักสูตรอาชีวะ/เทียบโอนที่ลดค่าใช้จ่าย พร้อมยื่น กยศ. และทุนของสถาบัน"
    elif budget.startswith("ปานกลาง"):
        study_route = "มองหามหาวิทยาลัยรัฐในภูมิภาค หลักสูตรสหกิจศึกษา และทุนผลการเรียน/ทุนขาดแคลน เพื่อควบคุมค่าเทอมและเพิ่มประสบการณ์"
    else:
        study_route = "เปิดทางเลือกมหาวิทยาลัยรัฐ เอกชน หรือหลักสูตรนานาชาติที่ตรงความถนัด โดยเปรียบเทียบผลลัพธ์การเรียน ทุน และโอกาสฝึกงานก่อนค่าเทอม"

    if constraints["location"].startswith("จำกัด"):
        study_route += " เนื่องจากการเดินทางจำกัด ให้เริ่มจากสถาบันในจังหวัดหรือพื้นที่ใกล้เคียง และเทียบค่าเดินทางกับค่าหอพักจริง"
    else:
        study_route += " เนื่องจากย้ายที่อยู่ได้ ให้เทียบตัวเลือกจากคุณภาพหลักสูตร เครือข่ายฝึกงาน และค่าครองชีพรวม"

    if constraints["burden"].startswith("มีภาระ"):
        study_route += " หากต้องมีรายได้เร็ว ให้พิจารณาหลักสูตรที่มีสหกิจ/ฝึกงานจริง หรือเส้นทางประกาศนียบัตรที่ต่อยอดปริญญาได้"

    st.markdown("### เส้นทางศึกษาต่อที่สอดคล้องกับทุน")
    st.info(study_route)
    st.markdown(
        f"**เป้าหมายงานเด่นของคุณ:** {max(goal_scores, key=goal_scores.get)}  \n"
        f"**รูปแบบที่เข้ากัน:** {constraints['job_style']}"
    )

    if constraints["scholarship"].startswith("สนใจมาก"):
        st.success("คุณเปิดรับทุนแบบมีเงื่อนไข: ควรค้นหาทุนที่ระบุสายงานชัด เช่น ทุนครู ทุนสาธารณสุข ทุนวิศวกรรม หรือทุนหน่วยงานรัฐ และอ่านเงื่อนไขใช้ทุนให้ครบก่อนสมัคร")
    else:
        st.warning("คุณต้องการอิสระหลังเรียนจบ: ให้เน้นทุนมอบเปล่า ทุนผลการเรียน ทุนขาดแคลน หรือทุนที่ไม่มีสัญญาผูกพัน และวางแผนค่าใช้จ่ายรายเทอมไว้ล่วงหน้า")

    st.markdown("### ทำไม MBTI นี้จึงเข้ากับสายงานข้างต้น")
    st.write(
        f"{mbti} ({profile['title']}) มีจุดเด่นด้าน {', '.join(stack[:2])} เป็นแกนหลัก "
        f"จึงมักเรียนรู้และทำงานได้ดีเมื่อได้ใช้ {', '.join(interest_data['functions'][:3])} "
        "ร่วมกับความสนใจที่คุณให้คะแนนสูง การเลือกสายงานที่ดีควรมีทั้งงานที่ใช้จุดแข็ง "
        "พื้นที่ให้พัฒนา และสภาพแวดล้อมที่ไม่ขัดกับข้อจำกัดชีวิตของคุณ"
    )


def render_results() -> None:
    function_scores, interest_scores, goal_scores = calculate_scores()
    mbti, fit_scores = infer_mbti(function_scores)
    profile = TYPE_PROFILES[mbti]
    stack = MBTI_STACKS[mbti]
    constraints = get_constraints()

    st.markdown("### ผลลัพธ์การวิเคราะห์ของคุณ")
    st.caption("ระบบจัดอันดับจากคะแนนเฉลี่ย 1–5 ที่แปลงเป็น 0–100 และเทียบกับลำดับ Cognitive Function ของแต่ละ MBTI")
    type_col, title_col = st.columns([1, 2])
    with type_col:
        st.markdown(
            f"""
            <div class="result-card">
            <div class="result-label">MBTI ที่เข้ากันมากที่สุด</div>
            <div class="result-value">{mbti}</div>
            <div>{profile['title']}</div>
            </div>
            """,
            unsafe_allow_html=True,
        )
    with title_col:
        st.markdown(
            f"""
            <div class="result-card">
            <div class="result-label">ภาพรวมตัวตน</div>
            <div style="font-size:1.08rem;line-height:1.6;margin-top:.45rem">{profile['overview']}</div>
            </div>
            """,
            unsafe_allow_html=True,
        )

    st.markdown("### กระบวนการคิดตามลำดับ Cognitive Stack")
    stack_columns = st.columns(4)
    stack_labels = ["Dominant", "Auxiliary", "Tertiary", "Inferior"]
    for column, label, function_key in zip(stack_columns, stack_labels, stack):
        function = next(item for item in FUNCTIONS if item["key"] == function_key)
        with column:
            st.markdown(
                f"""
                <div class="result-card">
                <div class="result-label">{label}</div>
                <div class="result-value">{function_key}</div>
                <div>{function['thai']}</div>
                <div class="small-note">คะแนน {function_scores[function_key]:.0f}/100</div>
                </div>
                """,
                unsafe_allow_html=True,
            )

    st.markdown("### กราฟเปรียบเทียบคะแนน Cognitive Functions")
    render_score_rows(function_scores)

    left, right = st.columns(2)
    with left:
        st.markdown("### จุดเด่นที่คุณโดดเด่น")
        for strength in profile["strengths"]:
            st.markdown(f"- {strength}")
    with right:
        st.markdown("### จุดที่ควรระวังและพัฒนา")
        for caution in profile["cautions"]:
            st.markdown(f"- {caution}")

    st.markdown("### ความถนัดรายวิชา")
    render_score_rows(interest_scores)

    render_path_recommendations(mbti, function_scores, interest_scores, goal_scores, constraints)

    st.markdown("### คะแนนความเข้ากันของ MBTI แต่ละแบบ")
    st.caption("ใช้ตรวจสอบว่าผลลัพธ์ใกล้เคียงกับตัวเลือกอื่นมากน้อยเพียงใด ไม่ควรอ่านเป็นคะแนนความเก่ง")
    render_score_rows(fit_scores)
    st.info("ถ้าคะแนนของ MBTI สองแบบใกล้กันมาก นั่นอาจสะท้อนว่าคุณปรับตัวได้หลายบริบท ผลลัพธ์นี้ควรใช้เป็นจุดเริ่มต้นสำหรับการสำรวจ ไม่ใช่กรอบจำกัดตัวเอง")

    if st.button("เริ่มทำแบบประเมินใหม่", type="primary", use_container_width=True):
        reset_assessment()
        st.rerun()


def main() -> None:
    init_state()
    render_styles()
    render_sidebar()
    render_header()
    total_pages = 12
    st.progress(min(st.session_state.page / (total_pages - 1), 1.0))

    if st.session_state.page == 0:
        render_intro()
    elif 1 <= st.session_state.page <= 8:
        render_cognitive_section(st.session_state.page - 1)
    elif st.session_state.page == 9:
        render_interest_section()
    elif st.session_state.page == 10:
        render_goals_and_constraints()
    else:
        render_results()


if __name__ == "__main__":
    main()
