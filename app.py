def render_cognitive_section(section_index: int) -> None:
    function = FUNCTIONS[section_index]
    st.markdown(f"### {function['key']} · {function['thai']}")
    st.caption(f"{function['name']} — ข้อ {section_index * 10 + 1}–{section_index * 10 + 10} จากทั้งหมด 80 ข้อ")
    st.write("ให้คะแนนตามพฤติกรรมที่เกิดขึ้นจริงกับคุณบ่อยที่สุด")
    with st.form(f"cognitive_form_{function['key']}"):
        current_values: dict[str, str] = {}
        for index, question in enumerate(function["questions"]):
            answer_key = f"cognitive_{function['key']}_{index}"
            saved = st.session_state.answers.get(answer_key, 3)
            current_values[answer_key] = st.radio(
                f"{section_index * 10 + index + 1}. {question}",
                LIKERT,
                index=saved - 1,
                key=f"input_{answer_key}",
                horizontal=True,
            )
        submitted = st.form_submit_button(
            "บันทึกและไปต่อ",
            type="primary",
            use_container_width=True,
        )
    if submitted:
        for key, value in current_values.items():
            st.session_state.answers[key] = likert_value(value)
        st.session_state.page += 1
        st.rerun()
    if st.session_state.page > 1 and st.button("ย้อนกลับ", key=f"back_{function['key']}"):
        st.session_state.page -= 1
        st.rerun()


