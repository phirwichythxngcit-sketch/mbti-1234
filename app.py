# --- อัลกอริทึมตรรกศาสตร์ (Logic Algorithm) ---
def get_opposite_function(func):
    """หาแกนตรงข้ามของฟังก์ชัน (เช่น Ne ตรงข้ามกับ Si)"""
    opposites = {
        "Ne": "Si", "Si": "Ne",
        "Ni": "Se", "Se": "Ni",
        "Te": "Fi", "Fi": "Te",
        "Ti": "Fe", "Fe": "Ti"
    }
    return opposites.get(func)

def calculate_mbti(scores):
    """ใช้อนุมานตรรกะเพื่อสร้าง Function Stack และหา MBTI"""
    # 1. เรียงลำดับคะแนนจากมากไปน้อย
    sorted_funcs = sorted(scores.items(), key=lambda x: x[1], reverse=True)
    
    # 2. หา Dominant Function (ฟังก์ชันที่คะแนนสูงสุด)
    dom = sorted_funcs[0][0]
    
    # 3. กำหนดคุณสมบัติของ Dominant
    dom_is_perceiving = dom[0] in ['N', 'S'] # เป็น P (รับรู้) หรือ J (ตัดสิน)
    dom_is_extraverted = dom[1] == 'e'       # เป็น E หรือ I
    
    # 4. หา Auxiliary Function (ต้องตรงข้ามกันทั้ง E/I และ J/P)
    target_p_j = 'J' if dom_is_perceiving else 'P'
    target_e_i = 'i' if dom_is_extraverted else 'e'
    
    aux = None
    for func, score in sorted_funcs[1:]:
        func_is_perceiving = func[0] in ['N', 'S']
        func_e_i = func[1]
        func_p_j = 'P' if func_is_perceiving else 'J'
        
        if func_p_j == target_p_j and func_e_i == target_e_i:
            aux = func
            break
            
    # กรณี Fallback (ถ้าคะแนนแปลกจนหา Aux ตามกฎไม่เจอ ให้เลือกฟังก์ชันที่มีคะแนนรองลงมา)
    if aux is None:
        aux = sorted_funcs[1][0]
        
    # 5. หา Tertiary และ Inferior
    tert = get_opposite_function(aux)
    inferior = get_opposite_function(dom)
    
    # 6. แมป MBTI จาก Dom และ Aux
    mbti_map = {
        ("Ne", "Ti"): "ENTP", ("Ne", "Fi"): "ENFP",
        ("Ni", "Te"): "INTJ", ("Ni", "Fe"): "INFJ",
        ("Se", "Ti"): "ESTP", ("Se", "Fi"): "ESFP",
        ("Si", "Te"): "ISTJ", ("Si", "Fe"): "ISFJ",
        ("Te", "Ni"): "ENTJ", ("Te", "Si"): "ESTJ",
        ("Ti", "Ne"): "INTP", ("Ti", "Se"): "ISTP",
        ("Fe", "Ni"): "ENFJ", ("Fe", "Si"): "ESFJ",
        ("Fi", "Ne"): "INFP", ("Fi", "Se"): "ISFP"
    }
    
    mbti_result = mbti_map.get((dom, aux), "Unidentified Type")
    return mbti_result, dom, aux, tert, inferior


