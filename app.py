# เตรียมคำถาม (Cache เพื่อไม่ให้โหลดใหม่และสลับตำแหน่งทุกครั้งที่กด)
@st.cache_data
def get_shuffled_questions():
    questions_list = []
    for func, qs in COGNITIVE_QUESTIONS.items():
        for q in qs:
            questions_list.append({"func": func, "text": q})
    random.shuffle(questions_list)
    return questions_list

all_questions = get_shuffled_questions()

st.title("🧠 แอปพลิเคชัน Cognitive Functions Test & GitHub Editor")
st.markdown("ทำแบบทดสอบ สำรวจฟังก์ชันความคิดของคุณ และสามารถเขียนโค้ดหรืออัปโหลดผลลัพธ์ขึ้น GitHub ได้ทันที")

# แบ่งหน้าด้วย Tabs
tab1, tab2, tab3 = st.tabs(["📝 1. ทำแบบทดสอบ", "📊 2. ผลลัพธ์", "☁️ 3. โค้ด & อัปโหลดขึ้น GitHub"])

# ----------------- TAB 1: แบบทดสอบ -----------------
with tab1:
    st.header("แบบประเมิน 80 ข้อ")
    st.write("ให้คะแนน 1-5 (1 = ไม่จริงเลย, 5 = ตรงกับตัวคุณมากที่สุด)")
    
    # ใช้ Form เพื่อป้องกันการโหลดหน้าเว็บใหม่ทุกครั้งที่เลื่อน Slider
    with st.form("cognitive_test_form"):
        answers = []
        for i, q in enumerate(all_questions):
            st.markdown(f"**ข้อ {i+1}:** {q['text']}")
            ans = st.slider(f"คะแนนข้อ {i+1}", 1, 5, 3, key=f"q_{i}", label_visibility="collapsed")
            answers.append({"func": q["func"], "score": ans})
            st.write("---")
            
        submitted = st.form_submit_button("✅ ประมวลผลลัพธ์")
        
        if submitted:
            # คำนวณคะแนน
            scores = {key: 0 for key in COGNITIVE_QUESTIONS.keys()}
            for item in answers:
                scores[item["func"]] += item["score"]
            st.session_state['test_results'] = scores
            st.success("ประมวลผลเสร็จสิ้น! กรุณาไปที่แท็บ '📊 2. ผลลัพธ์'")

# ----------------- TAB 2: ผลลัพธ์ -----------------
with tab2:
    st.header("ผลการทดสอบ Cognitive Functions")
    
    if 'test_results' in st.session_state:
        results = st.session_state['test_results']
        sorted_results = sorted(results.items(), key=lambda x: x[1], reverse=True)
        
        st.subheader("🏆 ฟังก์ชันที่โดดเด่นของคุณ (Leading Functions)")
        col1, col2 = st.columns(2)
        with col1:
            st.info(f"**อันดับ 1:** {sorted_results[0][0]} ({sorted_results[0][1]} คะแนน)")
        with col2:
            st.info(f"**อันดับ 2:** {sorted_results[1][0]} ({sorted_results[1][1]} คะแนน)")
            
        st.subheader("ตารางคะแนนทั้งหมด")
        for func, score in sorted_results:
            st.progress(score / 50.0, text=f"{func}: {score}/50")
            
        # สร้างข้อความสำหรับพร้อมอัปโหลด
        report_text = "### ผลทดสอบ Cognitive Functions\n\n"
        for func, score in sorted_results:
            report_text += f"- **{func}**: {score}/50\n"
        st.session_state['report_text'] = report_text
    else:
        st.warning("กรุณาทำแบบทดสอบในแท็บที่ 1 และกด 'ประมวลผลลัพธ์' ก่อนครับ")

# ----------------- TAB 3: GitHub Editor -----------------
with tab3:
    st.header("☁️ เขียนโค้ด รัน และอัปโหลดขึ้น GitHub")
    st.write("คุณสามารถเขียนโค้ด Python ทั่วไป หรือนำผลลัพธ์จากแท็บที่แล้วพุชขึ้น GitHub เป็นไฟล์ .md หรือ .py ได้")
    
    # แถบตั้งค่า GitHub
    st.markdown("#### ⚙️ ตั้งค่า GitHub")
    gh_col1, gh_col2, gh_col3 = st.columns(3)
    with gh_col1:
        github_token = st.text_input("GitHub Token (PAT)", type="password")
    with gh_col2:
        repo_name = st.text_input("ชื่อ Repository", placeholder="username/repo_name")
    with gh_col3:
        file_path = st.text_input("ชื่อไฟล์", placeholder="result.md หรือ script.py")
    
    commit_msg = st.text_input("Commit Message", value="Update from Streamlit Cognitive App")
    
    # กล่องข้อความ/โค้ด ที่ผู้ใช้สามารถแก้ไขได้
    st.markdown("#### 📝 Code Editor / File Content")
    
    # หากมีผลการทดสอบ ให้เป็นตัวเลือกเริ่มต้น
    default_content = st.session_state.get('report_text', "print('Hello, Cognitive Functions & GitHub!')")
    
    code_input = st.text_area("เขียนโค้ด Python หรือข้อความ Markdown ที่นี่", height=300, value=default_content)
    
    btn_col1, btn_col2 = st.columns(2)
    
    with btn_col1:
        if st.button("▶️ รันโค้ด Python (ถ้าเป็นไฟล์ Python)"):
            st.markdown("#### ผลลัพธ์ (Output):")
            f = io.StringIO()
            with redirect_stdout(f):
                try:
                    exec(code_input)
                    st.success("รันโค้ดสำเร็จ!")
                except Exception as e:
                    st.error(f"เกิดข้อผิดพลาด: {e}")
            output = f.getvalue()
            if output:
                st.code(output, language="text")
            
    with btn_col2:
        if st.button("☁️ พุชโค้ด/เนื้อหาขึ้น GitHub"):
            if not github_token or not repo_name or not file_path:
                st.warning("⚠️ กรุณากรอก GitHub Token, ชื่อ Repository และ ชื่อไฟล์ ให้ครบถ้วน")
            else:
                with st.spinner("กำลังเชื่อมต่อกับ GitHub..."):
                    try:
                        g = Github(github_token)
                        repo = g.get_repo(repo_name)
                        
                        try:
                            # กรณีมีไฟล์อยู่แล้วให้อัปเดต
                            contents = repo.get_contents(file_path)
                            repo.update_file(contents.path, commit_msg, code_input, contents.sha)
                            st.success(f"✅ อัปเดตไฟล์ `{file_path}` ใน `{repo_name}` สำเร็จ!")
                        except:
                            # กรณีไม่มีไฟล์ให้สร้างใหม่
                            repo.create_file(file_path, commit_msg, code_input)
                            st.success(f"✅ สร้างไฟล์ใหม่ `{file_path}` ใน `{repo_name}` สำเร็จ!")
                            
                    except Exception as e:
                        st.error(f"❌ เกิดข้อผิดพลาดในการเชื่อมต่อ GitHub: {e}")
